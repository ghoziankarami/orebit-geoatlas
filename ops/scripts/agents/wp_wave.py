"""Parallel multi-agent wave orchestration helpers and Antigravity workflow generator for Orebit GeoAtlas."""

from __future__ import annotations

import json

EXECUTOR_RESULT_SCHEMA = {
    "type": "object",
    "properties": {
        "wp": {"type": "string"},
        "branch": {"type": "string"},
        "worktree_path": {"type": "string"},
        "head_sha": {"type": "string"},
        "local_ci_passed": {"type": "boolean"},
        "targeted_tests_passed": {"type": "boolean"},
        "files_changed": {"type": "array", "items": {"type": "string"}},
        "summary": {"type": "string"},
        "dod_evidence": {"type": "array", "items": {"type": "string"}},
        "stop_reason": {"type": "string"},
    },
    "required": [
        "wp",
        "branch",
        "worktree_path",
        "head_sha",
        "local_ci_passed",
        "targeted_tests_passed",
        "summary",
    ],
}

REVIEWER_RESULT_SCHEMA = {
    "type": "object",
    "properties": {
        "wp": {"type": "string"},
        "verdict": {"type": "string", "enum": ["PASS", "NEEDS_FIX"]},
        "checked_sha": {"type": "string"},
        "findings": {"type": "array", "items": {"type": "string"}},
        "summary": {"type": "string"},
    },
    "required": ["wp", "verdict", "checked_sha", "findings", "summary"],
}


def validate_wave_lanes(wp_lanes: dict[str, list[str]]) -> list[str]:
    """Return conflict messages if any two WPs in a parallel wave share a non-HUMAN file lane."""
    owners: dict[str, str] = {}
    conflicts: list[str] = []
    for wp_id, lanes in wp_lanes.items():
        for lane in lanes:
            if lane == "HUMAN":
                continue
            if lane in owners:
                conflicts.append(
                    f"Lane conflict on {lane}: {owners[lane]} and {wp_id} cannot run in parallel"
                )
            else:
                owners[lane] = wp_id
    return conflicts


def validate_workflow_args(
    wp_ids: list[str], *, exec_model: str, review_model: str, max_cycles: int
) -> None:
    """Validate parallel workflow inputs before generating or executing a wave."""
    if not wp_ids:
        raise ValueError("Supply at least one WP ID.")
    seen: set[str] = set()
    dups = []
    for item in wp_ids:
        if item in seen:
            dups.append(item)
        seen.add(item)
    if dups:
        raise ValueError(f"Duplicate WP IDs in wave: {', '.join(sorted(set(dups)))}")
    if exec_model == review_model:
        raise ValueError("Executor and reviewer models must differ.")
    if max_cycles < 1:
        raise ValueError("max_cycles must be at least 1.")


def outcome_passed(wp_id: str, ex: dict, rv: dict) -> bool:
    """True only when executor and independent reviewer agree on the exact non-empty head SHA and all checks pass."""
    head_sha = (ex.get("head_sha") or "").strip()
    checked_sha = (rv.get("checked_sha") or "").strip()
    return bool(
        head_sha
        and ex.get("wp") == wp_id
        and rv.get("wp") == wp_id
        and checked_sha == head_sha
        and ex.get("local_ci_passed") is True
        and ex.get("targeted_tests_passed") is True
        and rv.get("verdict") == "PASS"
    )


def render_antigravity_workflow(
    wp_ids: list[str],
    *,
    exec_model: str = "flash",
    review_model: str = "pro",
    max_cycles: int = 2,
    base_ref: str = "main",
) -> str:
    """Generate a self-contained Antigravity `run_workflow` script for a parallel disjoint-lane wave."""
    validate_workflow_args(
        wp_ids,
        exec_model=exec_model,
        review_model=review_model,
        max_cycles=max_cycles,
    )
    return f"""# Auto-generated by `python3 ops/scripts/agents/wp.py workflow`
# Pass this script to Antigravity's `run_workflow(Script=..., Description=...)` tool.
import json
import subprocess
from pathlib import Path

ROOT = Path(WORKSPACES[0])
WP_IDS = {json.dumps(wp_ids)}
EXEC_MODEL = {json.dumps(exec_model)}
REVIEW_MODEL = {json.dumps(review_model)}
MAX_CYCLES = {int(max_cycles)}
BASE_REF = {json.dumps(base_ref)}

EXEC_SCHEMA = {json.dumps(EXECUTOR_RESULT_SCHEMA, indent=2)}
REVIEW_SCHEMA = {json.dumps(REVIEWER_RESULT_SCHEMA, indent=2)}

phase("1. Pack compact WP briefs (0 LLM tokens)")
briefs = {{}}
for wp_id in WP_IDS:
    data = json.loads(subprocess.check_output(
        ["python3", "ops/scripts/agents/wp.py", "brief", wp_id, "--json"],
        cwd=ROOT, text=True,
    ))
    briefs[wp_id] = {{
        "branch": data["branch"],
        "has_browser": bool(data["resolved_tests"]["pr_suites"]),
        "exec_md": subprocess.check_output(
            ["python3", "ops/scripts/agents/wp.py", "brief", wp_id, "--role", "executor"],
            cwd=ROOT, text=True,
        ),
        "review_md": subprocess.check_output(
            ["python3", "ops/scripts/agents/wp.py", "brief", wp_id, "--role", "reviewer"],
            cwd=ROOT, text=True,
        ),
    }}
log(f"Packed {{len(WP_IDS)}} disjoint-lane briefs: {{', '.join(WP_IDS)}}")

def verified_pass(wp_id, ex, rv):
    head = (ex.get("head_sha") or "").strip()
    return bool(
        head
        and ex.get("wp") == wp_id
        and rv.get("wp") == wp_id
        and (rv.get("checked_sha") or "").strip() == head
        and ex.get("local_ci_passed") is True
        and ex.get("targeted_tests_passed") is True
        and rv.get("verdict") == "PASS"
    )

async def run_one_wp(wp_id):
    branch = briefs[wp_id]["branch"]
    browser_flag = " --browser" if briefs[wp_id]["has_browser"] else ""
    executor = agent(
        f"Fast executor for {{wp_id}} on branch {{branch}}. Stay in lane, work in your isolated share workspace, run local-ci + fast-test, commit, return JSON with exact worktree_path and head_sha.",
        schema=EXEC_SCHEMA,
        role=f"Executor {{wp_id}}",
        workspace="share",
        model=EXEC_MODEL,
    )
    reviewer = agent(
        f"Independent read-only reviewer for {{wp_id}}. Never edit files. Return PASS or NEEDS_FIX JSON with exact checked_sha.",
        schema=REVIEW_SCHEMA,
        role=f"Reviewer {{wp_id}}",
        type_name="research",
        workspace="inherit",
        model=REVIEW_MODEL,
    )
    findings = None
    exec_res = {{}}
    review_res = {{}}
    cycles = 0
    try:
        for attempt in range(1, MAX_CYCLES + 1):
            cycles = attempt
            fix_block = ""
            if findings:
                fix_block = "\\n## Reviewer NEEDS_FIX Findings\\n" + "\\n".join(f"- {{x}}" for x in findings) + "\\n"
            exec_res = await executor(
                briefs[wp_id]["exec_md"] + fix_block
                + "\\nRun `bash ops/scripts/ci/local-ci.sh --fast` and `python3 ops/scripts/agents/wp.py fast-test "
                + wp_id + browser_flag + "`. Commit on branch `" + branch
                + "`, report your exact `worktree_path` (from `git rev-parse --show-toplevel`) and `head_sha` (40-char). Do NOT merge.",
                EXEC_SCHEMA,
            )
            head_sha = (exec_res.get("head_sha") or "").strip()
            wt_dir = (exec_res.get("worktree_path") or "").strip() or str(ROOT)
            if not head_sha:
                review_res = {{"wp": wp_id, "verdict": "NEEDS_FIX", "checked_sha": "", "findings": ["Executor returned empty head_sha."], "summary": "Missing head_sha"}}
                findings = review_res["findings"]
                continue
            diff_proc = subprocess.run(
                ["git", "-C", wt_dir, "diff", f"{{BASE_REF}}..{{head_sha}}", "--"],
                capture_output=True, text=True, encoding="utf-8", check=False,
            )
            if diff_proc.returncode != 0:
                review_res = {{"wp": wp_id, "verdict": "NEEDS_FIX", "checked_sha": head_sha, "findings": [f"git diff failed in {{wt_dir}}: {{diff_proc.stderr.strip()}}"], "summary": "Diff unreadable"}}
                findings = review_res["findings"]
                continue
            diff_text = diff_proc.stdout[:60000]
            if len(diff_proc.stdout) > 60000:
                diff_text += "\\n... [diff truncated at 60KB — inspect specific files read-only in worktree_path if needed]"
            review_res = await reviewer(
                briefs[wp_id]["review_md"]
                + "\\n## Executor Result\\n```json\\n" + json.dumps(exec_res, indent=2) + "\\n```"
                + "\\n## Exact Diff\\n```diff\\n" + diff_text + "\\n```",
                REVIEW_SCHEMA,
            )
            if verified_pass(wp_id, exec_res, review_res):
                break
            findings = review_res.get("findings") or ["Address reviewer findings and ensure local_ci_passed + targeted_tests_passed are true for exact head_sha."]
    finally:
        del executor
        del reviewer
    return {{"wp": wp_id, "exec": exec_res, "review": review_res, "cycles": cycles}}

phase(f"2. Execute + Independently Review {{len(WP_IDS)}} WPs in parallel")
outcomes = await parallel(WP_IDS, run_one_wp)

phase("3. Wave Summary")
rows = [
    "| WP | Branch | Head | Local CI | Targeted | Review | Cycles | Status |",
    "|---|---|---|---|---|---|---|---|",
]
for item in outcomes:
    ex, rv = item["exec"], item["review"]
    wp_id = item["wp"]
    ok = verified_pass(wp_id, ex, rv)
    rows.append(
        f"| {{wp_id}} | `{{ex.get('branch', '?')}}` | `{{(ex.get('head_sha') or '')[:10]}}` | "
        f"{{'PASS' if ex.get('local_ci_passed') else 'FAIL'}} | "
        f"{{'PASS' if ex.get('targeted_tests_passed') else 'FAIL'}} | "
        f"{{rv.get('verdict', '?')}} | {{item['cycles']}} | "
        f"{{'READY_FOR_OWNER_MERGE' if ok else 'ESCALATED_TO_OWNER'}} |"
    )
summary = "\\n".join(rows)
log(summary)
print(summary)
"""
