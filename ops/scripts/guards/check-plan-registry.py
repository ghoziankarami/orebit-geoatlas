#!/usr/bin/env python3
"""Every docs/PLAN-*.md declares its own status; the plan registry in AGENTS.md
and CLAUDE.md is generated from those declarations, never hand-maintained.

Contract:
  1. Line 1 of every `docs/PLAN-*.md` is exactly one of
     `<!-- plan-status: open -->` / `<!-- plan-status: closed -->`.
  2. The `plan-registry` block in AGENTS.md and CLAUDE.md is generated from those
     markers by `--write`, and verified byte-for-byte without it.

Static, stdlib only. Exit 0 clean, 1 on violations.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DOCS = ROOT / "docs"
MARKER = re.compile(r"^<!--\s*plan-status:\s*(open|closed)\s*-->\s*$")
HEADING = re.compile(r"^#\s+(\S.*?)\s*$")
TITLE_PREFIX = re.compile(r"^(?:PLAN|Plan)\s*[\u2014\u2013-]\s*")
BEGIN = "<!-- BEGIN plan-registry -->"
END = "<!-- END plan-registry -->"
NOTE = (
    "<!-- generated by ops/scripts/guards/check-plan-registry.py --write from the "
    "plan-status marker on line 1 of each docs/PLAN-*.md; do not edit by hand -->"
)
REGISTRY_DOCS = ("AGENTS.md", "CLAUDE.md")


def title_of(lines: list[str]) -> str:
    """The plan's own H1, minus a leading `PLAN — `, as a table-safe cell."""
    for line in lines[:6]:
        m = HEADING.match(line)
        if m:
            return TITLE_PREFIX.sub("", m.group(1)).replace("|", "\\|")
    return "(no H1 title)"


def collect() -> tuple[list[tuple[str, str, str]], list[str]]:
    """-> ([(relpath, status, title)], problems)."""
    entries: list[tuple[str, str, str]] = []
    problems: list[str] = []
    for path in sorted(DOCS.glob("PLAN-*.md")):
        rel = path.relative_to(ROOT).as_posix()
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
        hits = [i for i, line in enumerate(lines) if "plan-status:" in line]
        if len(hits) != 1:
            problems.append(
                f"{rel}: expected exactly one plan-status marker, found {len(hits)} "
                "(add `<!-- plan-status: open -->` as line 1)"
            )
            continue
        idx = hits[0]
        m = MARKER.match(lines[idx])
        if m is None:
            problems.append(
                f"{rel}:{idx + 1}: malformed marker, expected exactly "
                f"`<!-- plan-status: open -->` or `<!-- plan-status: closed -->`"
            )
            continue
        if idx != 0:
            problems.append(
                f"{rel}: marker must be line 1 (it is a machine-read field, not a "
                f"status note buried in prose), found on line {idx + 1}"
            )
            continue
        entries.append((rel, m.group(1), title_of(lines)))
    return entries, problems


def render_agents(entries: list[tuple[str, str, str]]) -> list[str]:
    opens = sorted((e for e in entries if e[1] == "open"), key=lambda e: e[0])
    closed = sorted((e for e in entries if e[1] == "closed"), key=lambda e: e[0])
    n = len(opens)
    head = f"**{n} open plan{'s' if n != 1 else ''}.**" if n else "**No open plans.**"
    rows = "\n".join(
        f"| `{rel}` | {'**OPEN**' if status == 'open' else 'closed'} | {title} |"
        for rel, status, title in opens + closed
    )
    return [
        BEGIN,
        NOTE,
        f"{head} Change the `plan-status` marker in the plan file itself, then re-run",
        "`ops/scripts/guards/check-plan-registry.py --write`. Open plans sort first.",
        "",
        "| Plan | Status | Title |",
        "|---|---|---|",
        *rows.splitlines(),
        END,
    ]


def render_claude(entries: list[tuple[str, str, str]]) -> list[str]:
    opens = sorted(e[0] for e in entries if e[1] == "open")
    if not opens:
        head = "**`docs/` holds no open plans.**"
    elif len(opens) == 1:
        head = f"**`docs/` holds one open plan** \u2014 `{opens[0]}`."
    else:
        head = (
            f"**`docs/` holds {len(opens)} open plans** \u2014 "
            + ", ".join(f"`{p}`" for p in opens)
            + "."
        )
    return [
        BEGIN,
        NOTE,
        f"{head} The full registry, statuses included, is the generated block in `AGENTS.md`.",
        "Never enumerate plans or count them by hand here \u2014 that prose is what drifted.",
        END,
    ]


def find_block(rel: str, lines: list[str]) -> tuple[int, int] | list[str]:
    begins = [i for i, line in enumerate(lines) if line.strip() == BEGIN]
    ends = [i for i, line in enumerate(lines) if line.strip() == END]
    if len(begins) != 1 or len(ends) != 1:
        return [
            f"{rel}: expected exactly one plan-registry block "
            f"(`{BEGIN}` ... `{END}`), found {len(begins)} begin(s), {len(ends)} end(s)"
        ]
    if ends[0] < begins[0]:
        return [f"{rel}: plan-registry `{END}` precedes `{BEGIN}`"]
    return begins[0], ends[0]


def check_doc(rel: str, expected: list[str]) -> list[str]:
    path = ROOT / rel
    if not path.exists():
        return [f"{rel}: missing"]
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    span = find_block(rel, lines)
    if isinstance(span, list):
        return span
    begin, end = span
    actual = lines[begin : end + 1]
    if len(actual) != len(expected):
        return [
            f"{rel}: plan-registry block is stale -- {len(actual)} lines, expected "
            f"{len(expected)}; re-run with --write"
        ]
    for i, (got, want) in enumerate(zip(actual, expected)):
        if got != want:
            return [
                f"{rel}:{begin + i + 1}: plan-registry block is stale --\n"
                f"  in file:  {got}\n  expected: {want}"
            ]
    return []


def write_doc(rel: str, expected: list[str]) -> None:
    path = ROOT / rel
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    span = find_block(rel, lines)
    if isinstance(span, list):
        raise SystemExit(
            rel + ": cannot --write: add the block delimiters by hand first, "
            f"on their own lines:\n  {BEGIN}\n  {END}"
        )
    begin, end = span
    path.write_text(
        "\n".join(lines[:begin] + expected + lines[end + 1 :]) + "\n", encoding="utf-8"
    )


def main(argv: list[str]) -> int:
    entries, problems = collect()
    expected = {
        "AGENTS.md": render_agents(entries),
        "CLAUDE.md": render_claude(entries),
    }
    if "--write" in argv:
        for p in problems:
            print(p)
        if problems:
            print(f"\n{len(problems)} problem(s); fix the markers before --write.")
            return 1
        for rel in REGISTRY_DOCS:
            write_doc(rel, expected[rel])
        opens = sum(1 for e in entries if e[1] == "open")
        print(
            f"plan registry: wrote {len(entries)} plan(s), {opens} open, into "
            + ", ".join(REGISTRY_DOCS)
        )
        return 0
    problems += [p for rel in REGISTRY_DOCS for p in check_doc(rel, expected[rel])]
    for p in problems:
        print(p)
    if problems:
        print(
            f"\n{len(problems)} problem(s). Fix the plan-status marker in the plan file, then "
            "re-run with --write."
        )
        return 1
    opens = sum(1 for e in entries if e[1] == "open")
    print(
        f"plan registry: OK ({len(entries)} plans, {opens} open) -- "
        + ", ".join(REGISTRY_DOCS)
        + " in sync"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
